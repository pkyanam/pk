const maxReloadHandoff = 4096

var reloadTokenPattern = regexp.MustCompile(`^[a-f0-9]{64}$`)

type reloadHandoff struct {
	Token         string `json:"token"`
	SupervisorPID int    `json:"owner_pid"`
	Workspace     string `json:"workspace"`
	SessionID     string `json:"session_id"`
	Model         string `json:"model"`
	Effort        string `json:"effort"`
}

// newReloadToken is generated by the Go supervisor and passed only to its
// OpenTUI/RPC descendants. The handoff file name is derived from this token,
// never from a UI-provided path.
func newReloadToken() (string, error) {
	var token [32]byte
	if _, err := rand.Read(token[:]); err != nil {
		return "", fmt.Errorf("create reload token: %w", err)
	}
	return hex.EncodeToString(token[:]), nil
}

// writeReloadHandoff persists the idle UI state for the current supervised
// launch. It is intended to be called by the RPC child after it has verified
// that there is no active turn or attached task.
func writeReloadHandoff(h reloadHandoff) error {
	token := os.Getenv("PK_RELOAD_TOKEN")
	if !reloadTokenPattern.MatchString(token) {
		return errors.New("reload is unavailable outside a supervised pk UI launch")
	}
	supervisorPID, err := strconv.Atoi(os.Getenv("PK_RELOAD_SUPERVISOR_PID"))
	if err != nil || supervisorPID <= 0 {
		return errors.New("invalid reload supervisor identity")
	}
	h.Token = token
	h.SupervisorPID = supervisorPID
	if err := validateReloadHandoff(&h, supervisorPID); err != nil {
		return err
	}
	root := filepath.Join(pkHome(), "reload")
	if err := ensurePrivateDirectory(filepath.Dir(root)); err != nil {
		return fmt.Errorf("prepare reload state: %w", err)
	}
	if err := os.MkdirAll(root, 0o700); err != nil {
		return fmt.Errorf("create reload state directory: %w", err)
	}
	rootInfo, err := os.Lstat(root)
	if err != nil || !rootInfo.IsDir() || rootInfo.Mode().Perm()&0o077 != 0 {
		return errors.New("reload state directory must be a private real directory")
	}
	if err := ensurePrivateDirectory(root); err != nil {
		return fmt.Errorf("prepare reload state: %w", err)
	}
	data, err := json.Marshal(h)
	if err != nil {
		return fmt.Errorf("encode reload handoff: %w", err)
	}
	if len(data) > maxReloadHandoff {
		return errors.New("reload handoff exceeds size limit")
	}
	path := reloadHandoffPath(root, token)
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		return fmt.Errorf("create reload handoff: %w", err)
	}
	if _, err := f.Write(data); err != nil {
		_ = f.Close()
		_ = os.Remove(path)
		return fmt.Errorf("write reload handoff: %w", err)
	}
	if err := f.Sync(); err != nil {
		_ = f.Close()
		_ = os.Remove(path)
		return fmt.Errorf("sync reload handoff: %w", err)
	}
	if err := f.Close(); err != nil {
		_ = os.Remove(path)
		return fmt.Errorf("close reload handoff: %w", err)
	}
	return nil
}

func consumeReloadHandoff(token string, supervisorPID int) (reloadHandoff, error) {
	if !reloadTokenPattern.MatchString(token) || supervisorPID <= 0 {
		return reloadHandoff{}, errors.New("invalid reload handoff identity")
	}
	root := filepath.Join(pkHome(), "reload")
	if err := ensurePrivateDirectory(filepath.Dir(root)); err != nil {
		return reloadHandoff{}, err
	}
	info, err := os.Lstat(root)
	if err != nil {
		return reloadHandoff{}, err
	}
	if !info.IsDir() || info.Mode().Perm()&0o077 != 0 {
		return reloadHandoff{}, errors.New("reload state directory must be private")
	}
	path := reloadHandoffPath(root, token)
	info, err = os.Lstat(path)
	if err != nil {
		return reloadHandoff{}, err
	}
	if !info.Mode().IsRegular() || info.Size() > maxReloadHandoff || info.Mode().Perm() != 0o600 {
		return reloadHandoff{}, errors.New("reload handoff file is not a bounded private regular file")
	}
	f, err := os.Open(path)
	if err != nil {
		return reloadHandoff{}, err
	}
	openedInfo, statErr := f.Stat()
	if statErr != nil {
		_ = f.Close()
		return reloadHandoff{}, statErr
	}
	if !openedInfo.Mode().IsRegular() || openedInfo.Mode().Perm() != 0o600 || !os.SameFile(info, openedInfo) {
		_ = f.Close()
		return reloadHandoff{}, errors.New("reload handoff changed while opening")
	}
	data, readErr := io.ReadAll(io.LimitReader(f, maxReloadHandoff+1))
	closeErr := f.Close()
	if readErr != nil {
		return reloadHandoff{}, readErr
	}
	if closeErr != nil {
		return reloadHandoff{}, closeErr
	}
	if len(data) > maxReloadHandoff {
		return reloadHandoff{}, errors.New("reload handoff exceeds size limit")
	}
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.DisallowUnknownFields()
	var h reloadHandoff
	if err := decoder.Decode(&h); err != nil {
		return reloadHandoff{}, fmt.Errorf("decode reload handoff: %w", err)
	}
	if err := decoder.Decode(new(any)); err != io.EOF {
		return reloadHandoff{}, errors.New("reload handoff must contain one JSON object")
	}
	if err := validateReloadHandoff(&h, supervisorPID); err != nil {
		return reloadHandoff{}, err
	}
	if h.Token != token {
		return reloadHandoff{}, errors.New("reload handoff token does not match this launch")
	}
	if err := os.Remove(path); err != nil {
		return reloadHandoff{}, fmt.Errorf("consume reload handoff: %w", err)
	}
	return h, nil
}

func validateReloadHandoff(h *reloadHandoff, supervisorPID int) error {
	if h.Token != "" && !reloadTokenPattern.MatchString(h.Token) {
		return errors.New("invalid reload token")
	}
	if h.SupervisorPID != supervisorPID {
		return errors.New("reload handoff belongs to a different supervisor")
	}
	if h.SessionID == "" || len(h.SessionID) > 128 || !safeReloadText(h.SessionID) {
		return errors.New("invalid reload session ID")
	}
	if h.Model == "" || len(h.Model) > 128 || !safeReloadText(h.Model) {
		return errors.New("invalid reload model ID")
	}
	if !config.ValidEffort(h.Effort) {
		return errors.New("invalid reload reasoning effort")
	}
	if !filepath.IsAbs(h.Workspace) || len(h.Workspace) > 4096 || !safeReloadText(h.Workspace) {
		return errors.New("reload workspace must be a bounded absolute path")
	}
	abs, err := filepath.Abs(h.Workspace)
	if err != nil || filepath.Clean(abs) != filepath.Clean(h.Workspace) {
		return errors.New("reload workspace must be a clean absolute path")
	}
	resolved, err := filepath.EvalSymlinks(h.Workspace)
	if err != nil {
		return errors.New("reload workspace is no longer available")
	}
	info, err := os.Stat(resolved)
	if err != nil || !info.IsDir() {
		return errors.New("reload workspace must be an existing directory")
	}
	h.Workspace = resolved
	h.Effort = strings.ToLower(h.Effort)
	return nil
}

func safeReloadText(value string) bool {
	if !utf8.ValidString(value) {
		return false
	}
	for _, r := range value {
		if unicode.IsControl(r) {
			return false
		}
	}
	return strings.TrimSpace(value) == value
}

func reloadHandoffPath(root, token string) string {
	return filepath.Join(root, token+".json")
}

// reloadLaunchArgs contains only validated values from the handoff. The
// launcher itself always comes from PK_BIN_DIR/default install configuration.
func reloadLaunchArgs(h reloadHandoff) []string {
	return []string{"--workspace", h.Workspace, "--session", h.SessionID, "--model", h.Model, "--effort", h.Effort}
}
